#!/usr/bin/env python3
"""Generate the typed API clients in sdk/ from api/openapi.yaml.

    python3 tools/generate_sdk.py           # write sdk/typescript/src/index.ts and sdk/python/arkism_client/__init__.py
    python3 tools/generate_sdk.py --check   # fail when the committed clients are not current

Standard library only. The spec file is JSON (a YAML subset), so json reads it.
"""

import argparse
import json
import keyword
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "api" / "openapi.yaml"
TS_OUT = ROOT / "sdk" / "typescript" / "src" / "index.ts"
PY_OUT = ROOT / "sdk" / "python" / "arkism_client" / "__init__.py"
METHODS = ("get", "post", "put", "patch", "delete")
HEADER = "Code generated by tools/generate_sdk.py from api/openapi.yaml. DO NOT EDIT."


def ref_name(ref):
    return ref.rsplit("/", 1)[-1]


def ts_type(s, depth=0):
    """TypeScript type of a JSON Schema; anything unsupported is unknown."""
    if not isinstance(s, dict) or depth > 40:
        return "unknown"
    if "$ref" in s:
        return ref_name(s["$ref"])
    if "const" in s:
        return json.dumps(s["const"], ensure_ascii=False)
    if "enum" in s:
        return " | ".join(json.dumps(v, ensure_ascii=False) for v in s["enum"]) or "never"
    for key, sep in (("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")):
        if key in s:
            return "(" + sep.join(ts_type(x, depth + 1) for x in s[key]) + ")"
    t = s.get("type")
    if isinstance(t, list):
        return "(" + " | ".join(ts_type(dict(s, type=x), depth + 1) for x in t) + ")"
    if t == "array":
        return "Array<" + ts_type(s.get("items"), depth + 1) + ">"
    if t == "object" or "properties" in s:
        return ts_object(s, depth)
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}.get(t, "unknown")


def ts_object(s, depth):
    required = set(s.get("required", []))
    props = s.get("properties", {})
    fields = [f"{json.dumps(k, ensure_ascii=False)}{'' if k in required else '?'}: {ts_type(v, depth + 1)}" for k, v in props.items()]
    extra = s.get("additionalProperties", not props)
    if extra is not False:
        # Declared fields must fit the index signature, so it widens to unknown beside them.
        fields.append("[key: string]: " + ("unknown" if props or extra is True else ts_type(extra, depth + 1)))
    return "{ " + "; ".join(fields) + " }" if fields else "{ [key: string]: never }"


def operations(spec):
    seen = set()
    for path, item in spec["paths"].items():
        for method in METHODS:
            op = item.get(method)
            if op is None:
                continue
            name = op.get("operationId") or method + "".join(w[:1].upper() + w[1:] for w in re.split(r"[^A-Za-z0-9]+", path.replace("{", "by_")) if w)
            name = re.sub(r"[^A-Za-z0-9_]", "_", name)
            base, n = name, 2
            while name in seen:
                name, n = f"{base}{n}", n + 1
            seen.add(name)
            yield name, method, path, op


def body_schema(op):
    content = (op.get("requestBody") or {}).get("content", {})
    if "application/json" in content:
        return content["application/json"].get("schema", {}), op["requestBody"].get("required", False)
    return None, False


def response_schema(op):
    for code, r in sorted(op.get("responses", {}).items()):
        if code.startswith("2"):
            return (r.get("content") or {}).get("application/json", {}).get("schema")
    return None


def ts_method(name, method, path, op):
    params = op.get("parameters", [])
    path_params = [p["name"] for p in params if p.get("in") == "path"]
    query = [p for p in params if p.get("in") == "query"]
    args = [f"{camel(p)}: string" for p in path_params]
    optional = []
    if query:
        fields = "; ".join(f"{json.dumps(p['name'])}{'' if p.get('required') else '?'}: {ts_type(p.get('schema'))}" for p in query)
        if any(p.get("required") for p in query):
            args.append(f"query: {{ {fields} }}")
        else:
            optional.append(f"query?: {{ {fields} }}")
    body, body_required = body_schema(op)
    if body is not None:
        (args if body_required else optional).append(f"body{'' if body_required else '?'}: {ts_type(body)}")
    args += optional  # a required parameter cannot follow an optional one
    url = re.sub(r"\{([^}]+)\}", lambda m: "${encodeURIComponent(" + camel(m.group(1)) + ")}", path)
    result = response_schema(op)
    doc = " ".join(str(op.get("summary", "")).split()).replace("*/", "*\\/")
    return (f"  /** {method.upper()} {path}{(' — ' + doc) if doc else ''} */\n"
            f"  {name}({', '.join(args)}): Promise<{ts_type(result) if result else 'unknown'}> {{\n"
            f"    return this.request({json.dumps(method.upper())}, `{url}`, {'query' if query else 'undefined'}, {'body' if body is not None else 'undefined'});\n"
            "  }\n")


def camel(name):
    parts = re.split(r"[^A-Za-z0-9]+", name)
    out = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    return out + "_" if out in ("delete", "default", "function", "new", "class") else out


TS_RUNTIME = '''export interface ClientOptions {
  /** Server base URL, e.g. http://127.0.0.1:8080 */
  baseUrl: string;
  /** Bearer token of a principal (memory-principal issue). */
  token?: string;
  headers?: { [key: string]: string };
  fetch?: typeof fetch;
}

/** A non-2xx answer; body is the server's JSON error ({code, ...}) when it sent one. */
export class ArkismError extends globalThis.Error {
  readonly status: number;
  readonly body: unknown;
  constructor(status: number, body: unknown) {
    super(`arkism api ${status}`);
    this.status = status;
    this.body = body;
  }
}

type Query = { [key: string]: string | number | boolean | undefined | null | Array<string | number | boolean> };

export class ArkismClient {
  private readonly opts: ClientOptions;

  constructor(opts: ClientOptions) {
    this.opts = { ...opts, baseUrl: opts.baseUrl.replace(/\\/+$/, "") };
  }

  /** Any route, including ones newer than this client. */
  async request<T = unknown>(method: string, path: string, query?: object, body?: unknown): Promise<T> {
    const url = new URL(this.opts.baseUrl + path);
    for (const [k, v] of Object.entries((query ?? {}) as Query)) {
      if (v === undefined || v === null) continue;
      for (const item of Array.isArray(v) ? v : [v]) url.searchParams.append(k, String(item));
    }
    const headers: { [key: string]: string } = { Accept: "application/json", ...this.opts.headers };
    if (this.opts.token) headers.Authorization = `Bearer ${this.opts.token}`;
    if (body !== undefined) headers["Content-Type"] = "application/json";
    const res = await (this.opts.fetch ?? fetch)(url, { method, headers, body: body === undefined ? undefined : JSON.stringify(body) });
    const text = await res.text();
    let parsed: unknown = text;
    try {
      parsed = text ? JSON.parse(text) : undefined;
    } catch {
      // not JSON: keep the text
    }
    if (!res.ok) throw new ArkismError(res.status, parsed);
    return parsed as T;
  }

'''

PY_RUNTIME = '''import json
import urllib.error
import urllib.parse
import urllib.request


class ArkismError(Exception):
    """A non-2xx answer; body is the server's JSON error when it sent one."""

    def __init__(self, status, body):
        super().__init__(f"arkism api {status}")
        self.status = status
        self.body = body


class BaseClient:
    """Transport for ArkismClient: JSON over HTTP with a bearer token."""

    def __init__(self, base_url, token=None, timeout=30, headers=None):
        self.base_url = base_url.rstrip("/")
        self.token = token
        self.timeout = timeout
        self.headers = dict(headers or {})

    def request(self, method, path, query=None, body=None):
        """Any route, including ones newer than this client."""
        url = self.base_url + path
        pairs = [(k, v) for k, v in (query or {}).items() if v is not None]
        if pairs:
            url += "?" + urllib.parse.urlencode(pairs, doseq=True)
        headers = {"Accept": "application/json", **self.headers}
        if self.token:
            headers["Authorization"] = "Bearer " + self.token
        data = None
        if body is not None:
            headers["Content-Type"] = "application/json"
            data = json.dumps(body).encode()
        req = urllib.request.Request(url, data=data, headers=headers, method=method)
        try:
            with urllib.request.urlopen(req, timeout=self.timeout) as res:
                return _decode(res.read())
        except urllib.error.HTTPError as err:
            raise ArkismError(err.code, _decode(err.read())) from None


def _decode(raw):
    if not raw:
        return None
    try:
        return json.loads(raw)
    except ValueError:
        return raw.decode(errors="replace")

'''


def py_name(name):
    out = re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", name).lower()
    return out + "_" if keyword.iskeyword(out) else out


def py_method(name, method, path, op):
    params = op.get("parameters", [])
    path_params = [p["name"] for p in params if p.get("in") == "path"]
    has_query = any(p.get("in") == "query" for p in params)
    body, _ = body_schema(op)
    args = ["self"] + [py_name(camel(p)) for p in path_params]
    if has_query:
        args.append("query=None")
    if body is not None:
        args.append("body=None")
    url = re.sub(r"\{([^}]+)\}", lambda m: "{urllib.parse.quote(" + py_name(camel(m.group(1))) + ", safe='')}", path)
    doc = " ".join(str(op.get("summary", "")).split()).replace('"""', "'''").replace("\\", "\\\\")
    return (f"    def {py_name(name)}({', '.join(args)}):\n"
            f'        """{method.upper()} {path}{(" — " + doc) if doc else ""}"""\n'
            f"        return self.request({json.dumps(method.upper())}, f\"{url}\", {'query' if has_query else 'None'}, {'body' if body is not None else 'None'})\n\n")


def render(spec):
    ops = list(operations(spec))
    ts = [f"// {HEADER}\n// API version {spec['info']['version']}.\n/* eslint-disable */\n\n"]
    for name, schema in spec["components"]["schemas"].items():
        ts.append(f"export type {name} = {ts_type(schema)};\n")
    ts.append("\n" + TS_RUNTIME)
    ts.extend(ts_method(*op) for op in ops)
    ts.append("}\n")
    py = [f'"""Arkism API client. {HEADER}"""\n\n', PY_RUNTIME, "\n", "class ArkismClient(BaseClient):\n    \"\"\"Thin client: one method per route, plain dicts in and out.\"\"\"\n\n"]
    py.extend(py_method(*op) for op in ops)
    return "".join(ts), "".join(py).rstrip() + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when the generated clients are stale")
    args = parser.parse_args(argv)
    spec = json.loads(SPEC.read_text(encoding="utf-8"))
    ts, py = render(spec)
    stale = [p for p, text in ((TS_OUT, ts), (PY_OUT, py)) if not p.exists() or p.read_text(encoding="utf-8") != text]
    if args.check:
        for p in stale:
            print(f"{p.relative_to(ROOT)} is stale: run python3 tools/generate_sdk.py", file=sys.stderr)
        return 1 if stale else 0
    for p, text in ((TS_OUT, ts), (PY_OUT, py)):
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
